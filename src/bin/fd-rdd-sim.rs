use std::fs;
use std::path::{Path, PathBuf};

use anyhow::Context;
use clap::{Parser, Subcommand, ValueEnum};
use fd_rdd::config::{Config, L3ScanPolicy, WatchMode};
use fd_rdd::sim::{
    adversarial_report, default_regression_policy, evolve_report, grid_report, optimize_report,
    sim_regression_markdown, sim_regression_report, single_report,
    tiered_watch_config_patch_toml_from_reports, tiered_watch_recommendation_from_report,
    write_existing_parent, BenchmarkReport, OptimizerConfig, PolicyParams, SimRegressionReport,
    TieredWatchRecommendation, WorkloadConfig, WorkloadProfile,
};

#[derive(Parser, Debug)]
#[command(
    name = "fd-rdd-sim",
    version,
    about = "Synthetic tiered watcher policy benchmark for fd-rdd"
)]
struct Args {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand, Debug)]
enum Command {
    /// Keep trying policy candidates until convergence or trial budget exhaustion.
    Optimize(OptimizeArgs),
    /// Run one policy against one synthetic world.
    Single(CommonArgs),
    /// Run a deterministic parameter grid.
    Grid(CommonArgs),
    /// Run a simple genetic search.
    Evolve(EvolveArgs),
    /// Run grid candidates against multiple hostile workload profiles.
    Adversarial(CommonArgs),
    /// Run fixed-seed small golden workloads and fail on policy regressions.
    Regression(RegressionArgs),
    /// Emit a config.toml patch from a JSON benchmark report recommendation.
    EmitConfig(EmitConfigArgs),
    /// Preview the full config.toml after applying a report recommendation.
    Apply(ApplyArgs),
}

#[derive(Parser, Debug, Clone)]
struct CommonArgs {
    /// Workload profile.
    #[arg(long, default_value = "developer")]
    profile: ProfileArg,

    /// Number of synthetic directories.
    #[arg(long, default_value_t = 1_000)]
    dirs: usize,

    /// Number of synthetic new-file events.
    #[arg(long, default_value_t = 10_000)]
    events: usize,

    /// Simulated duration in seconds.
    #[arg(long, default_value_t = 3_600)]
    duration_secs: u64,

    /// Deterministic seed.
    #[arg(long, default_value_t = 42)]
    seed: u64,

    /// Target discovery SLA in seconds.
    #[arg(long)]
    sla_secs: Option<u64>,

    /// Max estimated L0 recursive watch directory cost.
    #[arg(long)]
    max_watch_dirs: Option<u32>,

    /// L0 idle TTL before demotion.
    #[arg(long)]
    l0_idle_ttl_secs: Option<u64>,

    /// L1 warm scan interval.
    #[arg(long)]
    l1_scan_interval_secs: Option<u64>,

    /// L2 cold scan interval.
    #[arg(long)]
    l2_scan_interval_secs: Option<u64>,

    /// L3 scan policy: interval, validate_on_query, or disabled.
    #[arg(long, value_parser = parse_l3_scan_policy)]
    l3_scan_policy: Option<L3ScanPolicy>,

    /// L3 low-frequency scan interval used by interval policy.
    #[arg(long)]
    l3_scan_interval_secs: Option<u64>,

    /// Max directories scanned per tick.
    #[arg(long)]
    per_round_max_dirs: Option<usize>,

    /// Max synthetic files scanned per tick.
    #[arg(long)]
    per_round_max_files: Option<u64>,

    /// Number of best runs kept in grid/adversarial output.
    #[arg(long, default_value_t = 10)]
    top_n: usize,

    /// Optional JSON/TOML policy file. CLI flags still set workload fields.
    #[arg(long)]
    policy: Option<PathBuf>,

    /// Optional output report path. Stdout is always written when omitted.
    #[arg(long)]
    output: Option<PathBuf>,
}

#[derive(Parser, Debug, Clone)]
struct EvolveArgs {
    #[command(flatten)]
    common: CommonArgs,

    /// Number of generations.
    #[arg(long, default_value_t = 12)]
    generations: usize,

    /// Population size.
    #[arg(long, default_value_t = 24)]
    population: usize,
}

#[derive(Parser, Debug, Clone)]
struct OptimizeArgs {
    #[command(flatten)]
    common: CommonArgs,

    /// Maximum search generations.
    #[arg(long, default_value_t = 40)]
    generations: usize,

    /// Candidate policies per generation.
    #[arg(long, default_value_t = 48)]
    population: usize,

    /// Stop after this many generations without meaningful improvement.
    #[arg(long, default_value_t = 8)]
    patience: usize,

    /// Minimum objective improvement needed to reset patience.
    #[arg(long, default_value_t = 0.5)]
    min_delta: f64,

    /// Optimize against developer/burst/dormant/adversarial/home-desktop profiles together.
    #[arg(long, default_value_t = true, action = clap::ArgAction::Set)]
    robust_profiles: bool,

    /// Write current best report after every generation.
    #[arg(long)]
    checkpoint: Option<PathBuf>,

    /// Resume from a previous checkpoint report.
    #[arg(long)]
    resume: Option<PathBuf>,
}

#[derive(Parser, Debug, Clone)]
struct EmitConfigArgs {
    /// JSON report path generated by optimize/grid/evolve/adversarial/single.
    #[arg(long, required = true, num_args = 1..)]
    input: Vec<PathBuf>,

    /// Optional TOML patch output path. Stdout is used when omitted.
    #[arg(long)]
    output: Option<PathBuf>,
}

#[derive(Parser, Debug, Clone)]
struct ApplyArgs {
    /// JSON report path generated by optimize/grid/evolve/adversarial/single.
    #[arg(long)]
    input: PathBuf,

    /// Existing config.toml path. Defaults to the standard fd-rdd config path when present.
    #[arg(long)]
    config: Option<PathBuf>,

    /// Print the merged full config without writing it.
    #[arg(long)]
    dry_run: bool,
}

#[derive(Parser, Debug, Clone)]
struct RegressionArgs {
    /// Optional JSON/TOML policy file. Defaults to the built-in CI regression policy.
    #[arg(long)]
    policy: Option<PathBuf>,

    /// Optional JSON report output path. Stdout is used when omitted.
    #[arg(long)]
    output: Option<PathBuf>,

    /// Optional Markdown report output path.
    #[arg(long)]
    markdown_output: Option<PathBuf>,

    /// Optional previous regression JSON report used only for Markdown delta columns.
    #[arg(long)]
    baseline: Option<PathBuf>,
}

#[derive(Debug, Clone, Copy, ValueEnum)]
enum ProfileArg {
    Developer,
    Burst,
    Dormant,
    Adversarial,
    HomeDesktop,
}

impl From<ProfileArg> for WorkloadProfile {
    fn from(value: ProfileArg) -> Self {
        match value {
            ProfileArg::Developer => Self::Developer,
            ProfileArg::Burst => Self::Burst,
            ProfileArg::Dormant => Self::Dormant,
            ProfileArg::Adversarial => Self::Adversarial,
            ProfileArg::HomeDesktop => Self::HomeDesktop,
        }
    }
}

fn main() -> anyhow::Result<()> {
    let args = Args::parse();
    let (report, output) = match args.command {
        Command::Optimize(args) => {
            let output = args.common.output.clone();
            let mut config = config_from_common(args.common)?;
            config.generations = args.generations;
            config.population = args.population;
            config.patience = args.patience;
            config.min_delta = args.min_delta;
            config.robust_profiles = args.robust_profiles;
            config.checkpoint_path = args.checkpoint;
            config.resume_path = args.resume;

            eprintln!(
                "fd-rdd-sim optimize: {} generations × {} candidates ({} total trials)",
                args.generations,
                args.population,
                args.generations * args.population,
            );
            if config.workload.duration_secs >= 1800 {
                eprintln!(
                    "warning: duration_secs={} may result in very long run times; consider --duration-secs 600 for a quick test",
                    config.workload.duration_secs,
                );
            }

            (optimize_report(config)?, output)
        }
        Command::Single(common) => {
            let output = common.output.clone();
            (single_report(config_from_common(common)?), output)
        }
        Command::Grid(common) => {
            let output = common.output.clone();
            (grid_report(config_from_common(common)?), output)
        }
        Command::Evolve(args) => {
            let output = args.common.output.clone();
            let mut config = config_from_common(args.common)?;
            config.generations = args.generations;
            config.population = args.population;
            (evolve_report(config), output)
        }
        Command::Adversarial(common) => {
            let output = common.output.clone();
            (adversarial_report(config_from_common(common)?), output)
        }
        Command::Regression(args) => {
            let policy = if let Some(path) = &args.policy {
                load_policy(path)?
            } else {
                default_regression_policy()
            };
            let report = sim_regression_report(policy);
            let baseline = match &args.baseline {
                Some(path) => Some(read_regression_report(path)?),
                None => None,
            };
            if let Some(path) = args.markdown_output {
                let markdown = sim_regression_markdown(&report, baseline.as_ref());
                write_text_creating_parent(&path, markdown.as_bytes())?;
            }
            let json = serde_json::to_string_pretty(&report)?;
            if let Some(path) = args.output {
                write_text_creating_parent(&path, json.as_bytes())?;
            } else {
                println!("{json}");
            }
            if !report.passed {
                anyhow::bail!(
                    "fd-rdd-sim regression failed: {}/{} cases failed",
                    report.summary.failed_cases,
                    report.summary.total_cases
                );
            }
            return Ok(());
        }
        Command::EmitConfig(args) => {
            let reports = read_reports(&args.input)?;
            let toml_patch = tiered_watch_config_patch_toml_from_reports(&reports)?;
            if let Some(path) = args.output {
                write_existing_parent(&path, &toml_patch)?;
            } else {
                print!("{toml_patch}");
            }
            return Ok(());
        }
        Command::Apply(args) => {
            if !args.dry_run {
                anyhow::bail!(
                    "fd-rdd-sim apply currently supports only --dry-run and never writes config files"
                );
            }
            let reports = read_reports(&[args.input])?;
            let recommendation = tiered_watch_recommendation_from_report(&reports[0])?;
            let config = read_config_for_dry_run(args.config.as_deref())?;
            let merged = merge_tiered_watch_config(config, &recommendation)?;
            let toml = toml::to_string_pretty(&merged)?;
            print!("{toml}");
            return Ok(());
        }
    };

    let json = serde_json::to_string_pretty(&report)?;
    if let Some(path) = output {
        write_text_creating_parent(&path, json.as_bytes())?;
    } else {
        println!("{json}");
    }
    Ok(())
}

fn read_reports(paths: &[PathBuf]) -> anyhow::Result<Vec<BenchmarkReport>> {
    paths
        .iter()
        .map(|path| {
            let text = fs::read_to_string(path)
                .with_context(|| format!("failed to read report {}", path.display()))?;
            serde_json::from_str(&text)
                .with_context(|| format!("failed to parse JSON report {}", path.display()))
        })
        .collect()
}

fn read_regression_report(path: &Path) -> anyhow::Result<SimRegressionReport> {
    let text = fs::read_to_string(path)
        .with_context(|| format!("failed to read regression report {}", path.display()))?;
    serde_json::from_str(&text)
        .with_context(|| format!("failed to parse regression JSON report {}", path.display()))
}

fn write_text_creating_parent(path: &Path, contents: &[u8]) -> anyhow::Result<()> {
    if let Some(parent) = path
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
    {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create output directory {}", parent.display()))?;
    }
    fs::write(path, contents).with_context(|| format!("failed to write {}", path.display()))
}

fn read_config_for_dry_run(path: Option<&Path>) -> anyhow::Result<Config> {
    let path = path
        .map(PathBuf::from)
        .or_else(Config::config_path)
        .filter(|path| path.exists());
    let Some(path) = path else {
        return Ok(Config::default());
    };

    let text = fs::read_to_string(&path)
        .with_context(|| format!("failed to read config {}", path.display()))?;
    toml::from_str(&text).with_context(|| format!("failed to parse config {}", path.display()))
}

fn merge_tiered_watch_config(
    mut config: Config,
    recommendation: &TieredWatchRecommendation,
) -> anyhow::Result<Config> {
    config.watch_mode = match recommendation.watch_mode.as_str() {
        "tiered" => WatchMode::Tiered,
        "recursive" => WatchMode::Recursive,
        "off" => WatchMode::Off,
        other => anyhow::bail!("unsupported recommended watch_mode: {other}"),
    };
    config.tiered_watch.max_watch_dirs = recommendation.max_watch_dirs as usize;
    config.tiered_watch.scan_items_per_sec = recommendation.scan_items_per_sec;
    config.tiered_watch.scan_ms_per_tick = recommendation.scan_ms_per_tick;
    config.tiered_watch.l0_idle_ttl_secs = recommendation.l0_idle_ttl_secs;
    config.tiered_watch.l1_scan_interval_secs = recommendation.l1_scan_interval_secs;
    config.tiered_watch.l2_scan_interval_secs = recommendation.l2_scan_interval_secs;
    config.tiered_watch.l3_scan_policy = recommendation.l3_scan_policy;
    config.tiered_watch.l3_scan_interval_secs = recommendation.l3_scan_interval_secs;
    config.tiered_watch.l1_empty_scans_to_l2 = recommendation.l1_empty_scans_to_l2;
    config.tiered_watch.l2_empty_scans_to_l3 = recommendation.l2_empty_scans_to_l3;
    Ok(config)
}

fn config_from_common(args: CommonArgs) -> anyhow::Result<OptimizerConfig> {
    let mut policy = if let Some(path) = &args.policy {
        load_policy(path)?
    } else {
        PolicyParams::default()
    };
    if let Some(value) = args.sla_secs {
        policy.sla_secs = value;
    }
    if let Some(value) = args.max_watch_dirs {
        policy.max_watch_dirs = value;
    }
    if let Some(value) = args.l0_idle_ttl_secs {
        policy.l0_idle_ttl_secs = value;
    }
    if let Some(value) = args.l1_scan_interval_secs {
        policy.l1_scan_interval_secs = value;
    }
    if let Some(value) = args.l2_scan_interval_secs {
        policy.l2_scan_interval_secs = value;
    }
    if let Some(value) = args.l3_scan_policy {
        policy.l3_scan_policy = value;
    }
    if let Some(value) = args.l3_scan_interval_secs {
        policy.l3_scan_interval_secs = value;
    }
    if let Some(value) = args.per_round_max_dirs {
        policy.per_round_max_dirs = value;
    }
    if let Some(value) = args.per_round_max_files {
        policy.per_round_max_files = value;
    }

    Ok(OptimizerConfig {
        workload: WorkloadConfig {
            profile: args.profile.into(),
            dirs: args.dirs,
            events: args.events,
            duration_secs: args.duration_secs,
            seed: args.seed,
        },
        policy,
        top_n: args.top_n,
        ..OptimizerConfig::default()
    })
}

fn parse_l3_scan_policy(value: &str) -> Result<L3ScanPolicy, String> {
    value.parse()
}

fn load_policy(path: &PathBuf) -> anyhow::Result<PolicyParams> {
    let text = fs::read_to_string(path)?;
    match path.extension().and_then(|ext| ext.to_str()) {
        Some("json") => Ok(serde_json::from_str(&text)?),
        Some("toml") => Ok(toml::from_str(&text)?),
        Some(other) => anyhow::bail!("unsupported policy file extension: {other}"),
        None => anyhow::bail!("policy file must end in .json or .toml"),
    }
}
